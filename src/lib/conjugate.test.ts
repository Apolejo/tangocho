const expected = (cell: Written | string) =>
  typeof cell === 'string' ? { kana: cell } : { kanji: cell[0], kana: cell[1] };

const label = ({ kanji, kana }: { kanji?: string; kana: string }) =>
  kanji === undefined ? kana : `${kanji}（${kana}）`;

describe('FORMS', () => {
  it('lists the eight forms of SPEC §11, in order', () => {
    // Answer events store these ids (SPEC §10.1): never rename one.
    expect(FORMS).toEqual([
      '辞書形',
      'ます',
      'ません',
      'ました',
      'ませんでした',
      'て',
      'ない',
      'た',
    ]);
  });
});

describe('conjugate: the table', () => {
  for (const { word, forms } of TABLE) {
    describe(`${label(word)} group ${word.verbGroup}`, () => {
      for (const form of FORMS) {
        const want = expected(forms[form]);
        it(`${form} → ${label(want)}`, () => {
          expect(conjugate(word, form)).toEqual(want);
        });
      }
    });
  }
});

describe('conjugate: verbs that do not fit their group', () => {
  // The validator reports these (SPEC §5.5); the engine returns undefined instead of guessing.
  const misfits: Verb[] = [
    { kanji: '書く', kana: 'かく', verbGroup: 2 }, // group 2 ends in る
    { kanji: '食べる', kana: 'たべ', verbGroup: 2 }, // the reading isn't a verb
    { kanji: '書く', kana: 'かく', verbGroup: 3 }, // neither する nor 来る
    { kanji: '書く', kana: 'かう', verbGroup: 1 }, // written form and reading end differently
    { kanji: '書く', kana: 'かく' }, // no group
  ];
  for (const word of misfits) {
    it(`${label(word)} group ${word.verbGroup ?? 'none'}`, () => {
      for (const form of FORMS) expect(conjugate(word, form), form).toBeUndefined();
    });
  }
});
