/**
 * The conjugation table (SPEC §11): what `conjugate` returns for each verb and form, written
 * before the engine existed. One block per verb, like a textbook chart: the written form, then
 * the reading. Verbs written only in kana have just the reading.
 *
 * Checked row by row against: <chart>, <date>
 *
 * Never edit this file to make a test pass (CLAUDE.md). If a row looks wrong, stop and ask.
 */

type Verb = Pick<Word, 'kanji' | 'kana' | 'verbGroup'>;
type Written = readonly [kanji: string, kana: string];

interface Entry {
  word: Verb;
  forms: Record<ConjugationForm, Written | string>;
}

const verb = (
  kanji: string,
  kana: string,
  verbGroup: VerbGroup,
  forms: Record<ConjugationForm, Written>,
): Entry => ({ word: { kanji, kana, verbGroup }, forms });

const kanaVerb = (
  kana: string,
  verbGroup: VerbGroup,
  forms: Record<ConjugationForm, string>,
): Entry => ({ word: { kana, verbGroup }, forms });

